// Подключается ПОСЛЕ baza/assets.js и baza/data-items.js.
//
// Устроена как data-church.js: в каждом городе своя таверна со своими
// ценами. Движок цен НЕ знает — он отвечает только на «хватает ли» и «что
// станет». Новый город добавляется сюда, код не трогается.
//
// ТРИ МЕСТА НА КАРТИНКЕ, и каждое делает своё:
//   напитки  — список того, что наливают в этом городе;
//   комната  — спят ВСЕ разом, платят с человека;
//   припасы  — еда в дорогу, чтобы ночевать не в таверне.
//
// ПЛАТИТ ЛИБО ГЕРОЙ, ЛИБО ОБЩАК — решает кнопка в окне, и у игрока, и у
// Ведущего. Это отличие от церкви: там общак платит всегда, потому что
// поднять павшего — дело партии, а выпивка дело личное.
// ═══════════════════════════════════════════════════════════

    window.tavernsDB = {
        grivensburg: {
            name: 'Таверна Старого Гривенсбурга',
            city: 'Гривенсбург',
            art: 'assets/interface/taverna.webp',

            /* КОМНАТА. Цена С ЧЕЛОВЕКА, спят всегда все вместе: поодиночке
               ночевать в таверне незачем, а кто в поле — тот на припасах.
               Число и последствия названы в самой главе, сцена 15:
               «2 золотых с человека. Восстанавливает HP, ману и снимает
               ступень опьянения. Наступает новый день». */
            roomPrice: 2,

            /* ПРИПАСЫ. В базе предметов они стоят 4 — это цена вещи. Таверна
               берёт пять: свои накрутили. Так же устроена наценка в лавках. */
            provisionPrice: 5,
            provisionKey: 'provision',

            /* НАПИТКИ. В первой главе наливают ОДНО — настойка из яиц
               дракона. Остальные бутылки на картинке нарисованы для вида:
               Настойка из Пикси и Медовуха появятся позже, и тогда им нужны
               будут свои числа. Пока их тут нет нарочно — пустая строка в
               меню честнее, чем товар, который ничего не делает. */
            drinks: ['dragon_egg_tincture']
        }
    };

    /* Таверна по ключу. Нет такой — вернём первую, чтобы окно не падало на
       опечатке в названии города. Ровно как churchOf. */
    window.tavernOf = function (key) {
        var db = window.tavernsDB || {};
        return db[key] || db[Object.keys(db)[0]] || null;
    };
