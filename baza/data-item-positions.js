// Собирается инструментом gear-fitter.html. Руками править не нужно.
//
// Ключ: {раса}_{класс}_{пол}_v{вариант} -> {ключ вещи} -> {x,y,w,h,rot,z}
// x и y — ЦЕНТР, проценты от картинки героя.
//
// Зачем. Орк и человек сложены по-разному, и одна общая разметка не может
// посадить кирасу одинаково хорошо на обоих. Здесь у каждой вещи свои
// координаты для каждого телосложения.
//
// ЗАЧЕМ В КЛЮЧЕ ВАРИАНТ. У одного класса моделек две, и они РАЗНЫЕ: один
// толстый и большой, другой худой — в этом их смысл. Раньше варианта в
// ключе не было, обе модельки делили одну раскладку, и пояс, посаженный
// на толстого, висел на худом в воздухе.
//
// Чего тут НЕТ: кольца, амулет, магия и реликвии — они одинаковы для всех
// и живут в data-anchors.js.
//
// Посадки для вещи нет — клиент берёт обычный слот из разметки. Значит
// база наполняется постепенно и ничего не ломает, пока пустая.
// ═══════════════════════════════════════════════════════════

    window.itemPositions = {};

    /* Посадка вещи на конкретного героя. Вернёт null — берём слот.
       Ищем от точного к общему, и вот почему такой порядок:
         1) своя модель — раса_класс_пол_вариант;
         2) первый вариант того же героя — вторую модельку могли ещё не
            размечать, и пусть лучше вещь сядет приблизительно, чем уедет
            в слот по умолчанию;
         3) старый трёхчастный ключ — база, собранная до появления
            вариантов. Без этой ступени вся прежняя разметка разом
            перестала бы находиться.
         4) другой пол той же расы и класса — решение автора 30.09.2026:
            пол посадку не сбивает, примерочная показывает посадку другого
            пола, пока свою не поправили.
       Вариант не передали — считаем первым. Новая примерочная (30.09)
       пишет ключ без варианта (раса_класс_пол) — он в списке тоже. */
    window.itemFit = function (race, cls, gender, itemKey, variant) {
        var base = race + '_' + cls + '_' + gender;
        var other = race + '_' + cls + '_' + (gender === 'female' ? 'male' : 'female');
        var v = Number(variant) > 0 ? Number(variant) : 1;
        var tries = [base + '_v' + v, base + '_v1', base, other, other + '_v1'];
        for (var i = 0; i < tries.length; i++) {
            var h = window.itemPositions[tries[i]];
            if (h && h[itemKey]) {
                var fit=h[itemKey];
                var item=(window.masterItemsDB || {})[itemKey];
                if ((item && item.slot==='gloves' || /glove/i.test(itemKey)) && fit.layoutRevision!=='compact-slots-2026-10-08') {
                    fit=h[itemKey]=Object.assign({},fit,{x:89,y:71.5,layoutRevision:'compact-slots-2026-10-08'});
                }
                return fit;
            }
        }
        return null;
    };
