// В каждом городе свой храм со своими ценами: чем дальше от дома, тем
// дороже милость. Движок цен НЕ знает — он отвечает только на «хватает ли»
// и «что станет». Поэтому новый город добавляется сюда, а код не трогается.
//
// Кто платит: воскрешение — всегда ОБЩАК (поднять павшего — дело партии);
// пожертвование — по умолчанию карман жреца, галочкой — общак.
// ═══════════════════════════════════════════════════════════

    window.churchesDB = {
        grivensburg: {
            name: 'Храм Старого Гривенсбурга',
            city: 'Гривенсбург',
            icon: GITHUB_URL + 'assets/icons/store_icon.png',
            /* Поднять павшего: ПОЛНОЕ здоровье, в отличие от воскрешения
               жреца, которое даёт 25–100% за Веру и работает только в бою.
               Платит общак. */
            revivePrice: 5,
            /* Пожертвования наполняют Веру жреца (выше 100 не растёт).
               Тратится Вера на молитвы (25) и воскрешение (25/50/75/100).
               Видов пожертвования два: +50 и +100. */
            donations: [
                { id: 'humble',  name: 'Скромное пожертвование', price: 1, gain: 50 },
                { id: 'generous', name: 'Щедрое пожертвование',  price: 2, gain: 100 }
            ]
        }
    };

    /* Храм по ключу. Нет такого — вернём первый, чтобы окно не падало
       на опечатке в названии города. */
    window.churchOf = function (key) {
        var db = window.churchesDB || {};
        return db[key] || db[Object.keys(db)[0]] || null;
    };
