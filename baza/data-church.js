    window.churchesDB = {
        grivensburg: {
            name: 'Храм Старого Гривенсбурга',
            city: 'Гривенсбург',
            icon: GITHUB_URL + 'assets/icons/store_icon.png',
            /* Поднять павшего: ПОЛНОЕ здоровье, в отличие от воскрешения
               жреца, которое даёт четверть и работает только в бою. */
            revivePrice: 5,
            /* Пожертвования наполняют Веру жреца. Она тратится ступенями
               50 и 100, поэтому и видов пожертвования два. */
            donations: [
                { id: 'humble',  name: 'Скромное пожертвование', price: 1, gain: 50 },
                { id: 'generous', name: 'Щедрое пожертвование',  price: 2, gain: 100 }
            ]
        }
    };

    /* Храм по ключу. Нет такого — вернём первый, чтобы окно не падало
       на опечатке в названии города. */
    window.churchOf = function (key) {
        var db = window.churchesDB || {};
        return db[key] || db[Object.keys(db)[0]] || null;
    };
